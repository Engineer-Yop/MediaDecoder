"""Plain-text, Markdown and JSON renderings of a result."""
from __future__ import annotations

import json

from .config import APP_NAME, APP_VERSION

DISCLAIMER = ("All steps are ESTIMATED reconstructions inferred from the finished file. "
              "The real creation process cannot be known for certain.")

_FIELDS = (("prompt", "Prompt"), ("negative_prompt", "Negative prompt"), ("command", "Command"),
           ("settings", "Settings / actions"))


def _badge(step: dict) -> str:
    return "ESTIMATED" if step.get("estimated", True) else "FROM FILE METADATA"


def step_to_text(step: dict) -> str:
    lines = [f"STEP {step['number']}: {step['title']}  [{_badge(step)}]"]
    if step.get("time_range"):
        lines.append(f"Time range: {step['time_range']}")
    lines.append(f"Produces: {step.get('produces', '')}")
    lines.append(f"Tool: {step.get('tool', '')}")
    for key, label in _FIELDS:
        if step.get(key):
            lines.append(f"{label}:\n{step[key]}")
    if step.get("evidence"):
        lines.append(f"Evidence: {step['evidence']}")
    return "\n".join(lines)


def to_text(result: dict) -> str:
    r = result["recipe"]
    head = [r["title"], "=" * len(r["title"]), f"Source file: {result['file']['name']}",
            f"Summary: {r['summary']}", f"Likely origin: {r['likely_origin']} (confidence: {r['confidence']})",
            f"Style: {', '.join(r.get('style_keywords', []))}", "", DISCLAIMER, ""]
    body = [step_to_text(s) + "\n" + "-" * 60 for s in r["steps"]]
    return "\n".join(head) + "\n" + "\n".join(body) + "\n"


def all_steps_text(result: dict) -> str:
    return "\n\n".join(step_to_text(s) for s in result["recipe"]["steps"])


def _fence(text: str, lang: str = "text") -> str:
    fence = "````" if "```" in text else "```"
    return f"{fence}{lang}\n{text}\n{fence}"


def to_markdown(result: dict) -> str:
    r = result["recipe"]
    out = [f"# {r['title']}", "",
           f"**Source file:** `{result['file']['name']}`  ",
           f"**Likely origin:** {r['likely_origin']} (confidence: {r['confidence']})  ",
           f"**Style:** {', '.join(r.get('style_keywords', []))}", "",
           f"> {DISCLAIMER}", "", r["summary"], ""]
    for s in r["steps"]:
        out.append(f"## Step {s['number']}: {s['title']} `{_badge(s)}`")
        out.append("")
        if s.get("time_range"):
            out.append(f"- **Time range:** {s['time_range']}")
        out.append(f"- **Produces:** {s.get('produces', '')}")
        out.append(f"- **Tool:** {s.get('tool', '')}")
        out.append("")
        for key, label in _FIELDS:
            if s.get(key):
                lang = "powershell" if key == "command" else "text"
                out += [f"**{label}:**", "", _fence(s[key], lang), ""]
        if s.get("evidence"):
            out += [f"*Evidence:* {s['evidence']}", ""]
    meta = result.get("meta") or {}
    out.append(f"---\n*Generated by {APP_NAME} {APP_VERSION} with {meta.get('model', 'Claude')}.*")
    return "\n".join(out) + "\n"


def to_json(result: dict) -> str:
    payload = {"generator": f"{APP_NAME} {APP_VERSION}", "disclaimer": DISCLAIMER, **result}
    return json.dumps(payload, indent=2, ensure_ascii=False, default=str)
